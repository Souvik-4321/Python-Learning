#Multipication table using for loop
n = int(input("Enter a number: "))
for i in range(1,11):
    print(f"{n} x {i} = {n*i}")

# Multipication table using while loop
m = int(input("Enter a number: "))
i = 1
while(i<11):
    print(f"{m} x {i} = {m*i}")
    i+=1

# Reverse Multipication table
